-- LM Data Universe: core schema.
-- Users own workspaces; workspaces hold documents; a document holds user-defined
-- tables (doc_tables), their columns (doc_columns) and rows (doc_rows, values in
-- a jsonb keyed by column uuid), plus pages and the widgets laid out on them.

-- ============================================================
-- Profiles
-- ============================================================
create table public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  email text not null,
  full_name text,
  created_at timestamptz not null default now()
);

-- ============================================================
-- Workspaces and documents
-- ============================================================
create table public.workspaces (
  id uuid primary key default gen_random_uuid(),
  name text not null check (length(btrim(name)) between 1 and 120),
  owner_id uuid not null references public.profiles(id) on delete cascade,
  is_personal boolean not null default false,
  created_at timestamptz not null default now()
);

create table public.workspace_members (
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('owner', 'editor', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (workspace_id, user_id)
);
create index workspace_members_user_idx on public.workspace_members (user_id);

create table public.documents (
  id uuid primary key default gen_random_uuid(),
  workspace_id uuid not null references public.workspaces(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 200),
  created_by uuid references public.profiles(id) on delete set null default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index documents_workspace_idx on public.documents (workspace_id);

create table public.document_members (
  doc_id uuid not null references public.documents(id) on delete cascade,
  user_id uuid not null references public.profiles(id) on delete cascade,
  role text not null check (role in ('owner', 'editor', 'viewer')),
  created_at timestamptz not null default now(),
  primary key (doc_id, user_id)
);
create index document_members_user_idx on public.document_members (user_id);

-- ============================================================
-- Document contents
-- ============================================================
create table public.doc_tables (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.documents(id) on delete cascade,
  table_id text not null check (table_id ~ '^[A-Z][A-Za-z0-9_]{0,63}$'),
  position double precision not null default 0,
  created_at timestamptz not null default now(),
  unique (doc_id, table_id)
);

create table public.doc_columns (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.documents(id) on delete cascade,
  table_ref uuid not null references public.doc_tables(id) on delete cascade,
  col_id text not null check (col_id ~ '^[A-Za-z_][A-Za-z0-9_]{0,63}$'),
  label text not null default '',
  type text not null default 'Any' check (type in (
    'Any', 'Text', 'Numeric', 'Int', 'Bool', 'Date', 'DateTime',
    'Choice', 'ChoiceList', 'Ref', 'RefList'
  )),
  is_formula boolean not null default false,
  formula text not null default '',
  options jsonb not null default '{}'::jsonb,
  position double precision not null default 0,
  created_at timestamptz not null default now(),
  unique (table_ref, col_id)
);
create index doc_columns_doc_idx on public.doc_columns (doc_id);

create table public.doc_rows (
  id bigint generated by default as identity primary key,
  doc_id uuid not null references public.documents(id) on delete cascade,
  table_ref uuid not null references public.doc_tables(id) on delete cascade,
  manual_sort double precision not null default 0,
  data jsonb not null default '{}'::jsonb,
  created_by uuid default auth.uid(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);
create index doc_rows_table_sort_idx on public.doc_rows (table_ref, manual_sort);
create index doc_rows_doc_idx on public.doc_rows (doc_id);

create table public.doc_pages (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.documents(id) on delete cascade,
  name text not null check (length(btrim(name)) between 1 and 120),
  position double precision not null default 0,
  created_at timestamptz not null default now()
);
create index doc_pages_doc_idx on public.doc_pages (doc_id);

create table public.doc_widgets (
  id uuid primary key default gen_random_uuid(),
  doc_id uuid not null references public.documents(id) on delete cascade,
  page_id uuid not null references public.doc_pages(id) on delete cascade,
  table_ref uuid references public.doc_tables(id) on delete cascade,
  type text not null check (type in ('table', 'card', 'card_list', 'chart', 'summary', 'form')),
  title text not null default '',
  position double precision not null default 0,
  width smallint not null default 12 check (width between 3 and 12),
  height integer not null default 420 check (height between 160 and 2000),
  options jsonb not null default '{}'::jsonb,
  -- Linking: the widget whose selected row drives this one, and (optionally) the
  -- Ref column in this widget's table that points at the source's table.
  -- A null link_col with a link_source means "show the same record".
  link_source uuid references public.doc_widgets(id) on delete set null,
  link_col uuid references public.doc_columns(id) on delete set null,
  created_at timestamptz not null default now()
);
create index doc_widgets_doc_idx on public.doc_widgets (doc_id);
create index doc_widgets_page_idx on public.doc_widgets (page_id);

create table public.form_shares (
  id uuid primary key default gen_random_uuid(),
  token text not null unique default encode(extensions.gen_random_bytes(16), 'hex'),
  doc_id uuid not null references public.documents(id) on delete cascade,
  widget_id uuid not null unique references public.doc_widgets(id) on delete cascade,
  is_active boolean not null default true,
  created_at timestamptz not null default now()
);
create index form_shares_doc_idx on public.form_shares (doc_id);

-- ============================================================
-- Access helpers
-- ============================================================
create or replace function public.role_rank(p_role text)
returns int language sql immutable set search_path = '' as $$
  select case p_role when 'owner' then 3 when 'editor' then 2 when 'viewer' then 1 else 0 end
$$;

-- Documents the current user can reach with at least p_min rank
-- (1 viewer, 2 editor, 3 owner), directly or through their workspace.
create or replace function public.my_doc_ids(p_min int)
returns uuid[] language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(distinct s.doc_id), '{}')
  from (
    select dm.doc_id, public.role_rank(dm.role) as r
    from public.document_members dm
    where dm.user_id = auth.uid()
    union all
    select d.id, public.role_rank(wm.role)
    from public.documents d
    join public.workspace_members wm on wm.workspace_id = d.workspace_id
    where wm.user_id = auth.uid()
  ) s
  where s.r >= p_min
$$;

create or replace function public.my_workspace_ids(p_min int)
returns uuid[] language sql stable security definer set search_path = '' as $$
  select coalesce(array_agg(wm.workspace_id), '{}')
  from public.workspace_members wm
  where wm.user_id = auth.uid() and public.role_rank(wm.role) >= p_min
$$;

create or replace function public.doc_role(p_doc uuid)
returns text language sql stable security definer set search_path = '' as $$
  select case max(s.r) when 3 then 'owner' when 2 then 'editor' when 1 then 'viewer' end
  from (
    select public.role_rank(dm.role) as r
    from public.document_members dm
    where dm.doc_id = p_doc and dm.user_id = auth.uid()
    union all
    select public.role_rank(wm.role)
    from public.documents d
    join public.workspace_members wm on wm.workspace_id = d.workspace_id
    where d.id = p_doc and wm.user_id = auth.uid()
  ) s
$$;

-- Profiles visible to the current user: their own and anyone sharing a
-- workspace or document with them.
create or replace function public.can_see_profile(p_user uuid)
returns boolean language sql stable security definer set search_path = '' as $$
  select p_user = auth.uid()
    or exists (
      select 1 from public.workspace_members a
      join public.workspace_members b on b.workspace_id = a.workspace_id
      where a.user_id = auth.uid() and b.user_id = p_user
    )
    or exists (
      select 1 from public.document_members b
      where b.user_id = p_user and b.doc_id = any (public.my_doc_ids(1))
    )
$$;

-- ============================================================
-- Integrity triggers: doc_id always comes from the parent, never the client.
-- ============================================================
create or replace function public.tg_doc_id_from_table()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    new.doc_id := old.doc_id;
    new.table_ref := old.table_ref;
  else
    select t.doc_id into new.doc_id from public.doc_tables t where t.id = new.table_ref;
    if new.doc_id is null then
      raise exception 'Unknown table %', new.table_ref;
    end if;
  end if;
  return new;
end $$;

create trigger doc_columns_doc_id before insert or update on public.doc_columns
  for each row execute function public.tg_doc_id_from_table();
create trigger doc_rows_doc_id before insert or update on public.doc_rows
  for each row execute function public.tg_doc_id_from_table();

create or replace function public.tg_doc_tables_freeze()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.doc_id := old.doc_id;
  return new;
end $$;
create trigger doc_tables_freeze before update on public.doc_tables
  for each row execute function public.tg_doc_tables_freeze();
create trigger doc_pages_freeze before update on public.doc_pages
  for each row execute function public.tg_doc_tables_freeze();

create or replace function public.tg_widget_integrity()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    new.doc_id := old.doc_id;
  else
    select p.doc_id into new.doc_id from public.doc_pages p where p.id = new.page_id;
    if new.doc_id is null then
      raise exception 'Unknown page %', new.page_id;
    end if;
  end if;
  if not exists (select 1 from public.doc_pages p where p.id = new.page_id and p.doc_id = new.doc_id) then
    raise exception 'Page belongs to another document';
  end if;
  if new.table_ref is not null and not exists (
    select 1 from public.doc_tables t where t.id = new.table_ref and t.doc_id = new.doc_id
  ) then
    raise exception 'Table belongs to another document';
  end if;
  if new.link_source is not null and not exists (
    select 1 from public.doc_widgets w where w.id = new.link_source and w.doc_id = new.doc_id
  ) then
    raise exception 'Linked widget belongs to another document';
  end if;
  if new.link_col is not null and not exists (
    select 1 from public.doc_columns c where c.id = new.link_col and c.table_ref = new.table_ref
  ) then
    raise exception 'Link column must belong to the widget table';
  end if;
  return new;
end $$;
create trigger doc_widgets_integrity before insert or update on public.doc_widgets
  for each row execute function public.tg_widget_integrity();

create or replace function public.tg_form_share_doc()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if tg_op = 'UPDATE' then
    new.doc_id := old.doc_id;
    new.widget_id := old.widget_id;
    new.token := old.token;
  else
    select w.doc_id into new.doc_id from public.doc_widgets w where w.id = new.widget_id and w.type = 'form';
    if new.doc_id is null then
      raise exception 'Unknown form widget %', new.widget_id;
    end if;
  end if;
  return new;
end $$;
create trigger form_shares_doc before insert or update on public.form_shares
  for each row execute function public.tg_form_share_doc();

create or replace function public.tg_touch_row()
returns trigger language plpgsql set search_path = '' as $$
begin
  new.updated_at := now();
  return new;
end $$;
create trigger doc_rows_touch before update on public.doc_rows
  for each row execute function public.tg_touch_row();

-- Keep documents.updated_at roughly current without a write per keystroke.
create or replace function public.tg_touch_document()
returns trigger language plpgsql security definer set search_path = '' as $$
declare
  v_doc uuid := coalesce(new.doc_id, old.doc_id);
begin
  update public.documents set updated_at = now()
  where id = v_doc and updated_at < now() - interval '30 seconds';
  return null;
end $$;
create trigger doc_rows_touch_document after insert or update or delete on public.doc_rows
  for each row execute function public.tg_touch_document();
create trigger doc_columns_touch_document after insert or update or delete on public.doc_columns
  for each row execute function public.tg_touch_document();

-- Workspace creator becomes its owner; document creator becomes its owner.
create or replace function public.tg_workspace_owner()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.workspace_members (workspace_id, user_id, role)
  values (new.id, new.owner_id, 'owner')
  on conflict do nothing;
  return null;
end $$;
create trigger workspaces_owner after insert on public.workspaces
  for each row execute function public.tg_workspace_owner();

create or replace function public.tg_document_owner()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  if new.created_by is not null then
    insert into public.document_members (doc_id, user_id, role)
    values (new.id, new.created_by, 'owner')
    on conflict do nothing;
  end if;
  return null;
end $$;
create trigger documents_owner after insert on public.documents
  for each row execute function public.tg_document_owner();

-- New auth user: profile plus a personal workspace.
create or replace function public.handle_new_user()
returns trigger language plpgsql security definer set search_path = '' as $$
begin
  insert into public.profiles (id, email, full_name)
  values (new.id, coalesce(new.email, ''), nullif(new.raw_user_meta_data->>'full_name', ''));
  insert into public.workspaces (name, owner_id, is_personal)
  values ('Home', new.id, true);
  return new;
end $$;
create trigger on_auth_user_created after insert on auth.users
  for each row execute function public.handle_new_user();

