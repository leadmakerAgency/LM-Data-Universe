-- ============================================================
-- Sharing RPCs (owners only)
-- ============================================================
create or replace function public.share_document(p_doc uuid, p_email text, p_role text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid;
begin
  if public.doc_role(p_doc) is distinct from 'owner' then
    raise exception 'Only owners can share this document' using errcode = '42501';
  end if;
  if p_role not in ('owner', 'editor', 'viewer') then
    raise exception 'Invalid role %', p_role;
  end if;
  select id into v_user from public.profiles where lower(email) = lower(btrim(p_email));
  if v_user is null then
    raise exception 'No user with email %. They need to sign up first.', p_email using errcode = 'P0002';
  end if;
  insert into public.document_members (doc_id, user_id, role) values (p_doc, v_user, p_role)
  on conflict (doc_id, user_id) do update set role = excluded.role;
  return v_user;
end $$;

create or replace function public.remove_document_member(p_doc uuid, p_user uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if public.doc_role(p_doc) is distinct from 'owner' and p_user is distinct from auth.uid() then
    raise exception 'Only owners can remove members' using errcode = '42501';
  end if;
  if (select count(*) from public.document_members where doc_id = p_doc and role = 'owner' and user_id <> p_user) = 0
     and exists (select 1 from public.document_members where doc_id = p_doc and user_id = p_user and role = 'owner') then
    raise exception 'A document needs at least one owner';
  end if;
  delete from public.document_members where doc_id = p_doc and user_id = p_user;
end $$;

create or replace function public.share_workspace(p_workspace uuid, p_email text, p_role text)
returns uuid language plpgsql security definer set search_path = '' as $$
declare
  v_user uuid;
begin
  if not (p_workspace = any (public.my_workspace_ids(3))) then
    raise exception 'Only owners can share this workspace' using errcode = '42501';
  end if;
  if exists (select 1 from public.workspaces where id = p_workspace and is_personal) then
    raise exception 'Personal workspaces cannot be shared; share individual documents instead';
  end if;
  if p_role not in ('owner', 'editor', 'viewer') then
    raise exception 'Invalid role %', p_role;
  end if;
  select id into v_user from public.profiles where lower(email) = lower(btrim(p_email));
  if v_user is null then
    raise exception 'No user with email %. They need to sign up first.', p_email using errcode = 'P0002';
  end if;
  insert into public.workspace_members (workspace_id, user_id, role) values (p_workspace, v_user, p_role)
  on conflict (workspace_id, user_id) do update set role = excluded.role;
  return v_user;
end $$;

create or replace function public.remove_workspace_member(p_workspace uuid, p_user uuid)
returns void language plpgsql security definer set search_path = '' as $$
begin
  if not (p_workspace = any (public.my_workspace_ids(3))) and p_user is distinct from auth.uid() then
    raise exception 'Only owners can remove members' using errcode = '42501';
  end if;
  if exists (select 1 from public.workspaces where id = p_workspace and owner_id = p_user) then
    raise exception 'The workspace creator cannot be removed';
  end if;
  delete from public.workspace_members where workspace_id = p_workspace and user_id = p_user;
end $$;

-- ============================================================
-- Public forms
-- ============================================================
create or replace function public.get_public_form(p_token text)
returns jsonb language plpgsql stable security definer set search_path = '' as $$
declare
  v_widget public.doc_widgets;
  v_fields jsonb;
begin
  select w.* into v_widget
  from public.form_shares s join public.doc_widgets w on w.id = s.widget_id
  where s.token = p_token and s.is_active;
  if v_widget.id is null then
    return null;
  end if;
  select coalesce(jsonb_agg(jsonb_build_object(
      'id', c.id, 'label', coalesce(nullif(c.label, ''), c.col_id), 'type', c.type,
      'options', c.options - 'refTable', 'required', coalesce((f.value->>'required')::boolean, false),
      'help', coalesce(f.value->>'help', '')
    ) order by f.ordinality), '[]'::jsonb)
  into v_fields
  from jsonb_array_elements(coalesce(v_widget.options->'fields', '[]'::jsonb)) with ordinality f
  join public.doc_columns c on c.id = (f.value->>'col')::uuid
  where c.table_ref = v_widget.table_ref and not c.is_formula
    and c.type not in ('Ref', 'RefList');
  return jsonb_build_object(
    'title', coalesce(nullif(v_widget.options->>'formTitle', ''), nullif(v_widget.title, ''), 'Form'),
    'description', coalesce(v_widget.options->>'formDescription', ''),
    'submitLabel', coalesce(nullif(v_widget.options->>'submitLabel', ''), 'Submit'),
    'successMessage', coalesce(nullif(v_widget.options->>'successMessage', ''), 'Thank you! Your response has been recorded.'),
    'fields', v_fields
  );
end $$;

create or replace function public.submit_public_form(p_token text, p_values jsonb)
returns boolean language plpgsql volatile security definer set search_path = '' as $$
declare
  v_widget public.doc_widgets;
  v_data jsonb := '{}'::jsonb;
  v_field record;
  v_sort double precision;
begin
  if p_values is null or jsonb_typeof(p_values) <> 'object' or pg_column_size(p_values) > 65536 then
    raise exception 'Invalid submission';
  end if;
  select w.* into v_widget
  from public.form_shares s join public.doc_widgets w on w.id = s.widget_id
  where s.token = p_token and s.is_active;
  if v_widget.id is null then
    raise exception 'This form is not accepting responses';
  end if;
  for v_field in
    select c.id, coalesce((f.value->>'required')::boolean, false) as required
    from jsonb_array_elements(coalesce(v_widget.options->'fields', '[]'::jsonb)) f
    join public.doc_columns c on c.id = (f.value->>'col')::uuid
    where c.table_ref = v_widget.table_ref and not c.is_formula and c.type not in ('Ref', 'RefList')
  loop
    if p_values ? v_field.id::text and p_values->(v_field.id::text) <> 'null'::jsonb
       and p_values->(v_field.id::text) <> '""'::jsonb then
      v_data := v_data || jsonb_build_object(v_field.id::text, p_values->(v_field.id::text));
    elsif v_field.required then
      raise exception 'Please fill in all required fields';
    end if;
  end loop;
  select coalesce(max(manual_sort), 0) + 1 into v_sort from public.doc_rows where table_ref = v_widget.table_ref;
  insert into public.doc_rows (doc_id, table_ref, manual_sort, data, created_by)
  values (v_widget.doc_id, v_widget.table_ref, v_sort, v_data, null);
  return true;
end $$;

