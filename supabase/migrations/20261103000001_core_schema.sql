  using (doc_id = any ((select public.my_doc_ids(1))::uuid[]));

-- Content tables share one shape: viewers read, editors write.
do $$
declare
  t text;
begin
  foreach t in array array['doc_tables', 'doc_columns', 'doc_rows', 'doc_pages', 'doc_widgets'] loop
    execute format('create policy %1$s_select on public.%1$s for select to authenticated using (doc_id = any ((select public.my_doc_ids(1))::uuid[]))', t);
    execute format('create policy %1$s_insert on public.%1$s for insert to authenticated with check (doc_id = any ((select public.my_doc_ids(2))::uuid[]))', t);
    execute format('create policy %1$s_update on public.%1$s for update to authenticated using (doc_id = any ((select public.my_doc_ids(2))::uuid[])) with check (doc_id = any ((select public.my_doc_ids(2))::uuid[]))', t);
    execute format('create policy %1$s_delete on public.%1$s for delete to authenticated using (doc_id = any ((select public.my_doc_ids(2))::uuid[]))', t);
  end loop;
end $$;

