// Bundles packages/engine into the doc-worker Edge Function (npm run build:worker).
// The output is kept to printable ASCII so it survives copy/paste deploys.
import { build } from "esbuild";
import { readFileSync, writeFileSync } from "node:fs";

const outfile = "supabase/functions/doc-worker/engine.js";
await build({
  entryPoints: ["packages/engine/src/index.ts"],
  bundle: true,
  format: "esm",
  platform: "neutral",
  target: "es2022",
  minifyWhitespace: true,
  minifyIdentifiers: true,
  charset: "ascii",
  legalComments: "none",
  outfile,
});
// Control characters can only occur inside string literals: escape them.
const code = readFileSync(outfile, "utf8")
  .replace(/[\x00-\x09\x0b-\x1f\x7f]/g, (c) => `\\x${c.charCodeAt(0).toString(16).padStart(2, "0")}`)
  .trimEnd();
writeFileSync(outfile, `// Generated by scripts/build-worker.mjs from packages/engine. Do not edit.\n${code}\n`);
console.log(`${outfile}: ${code.length} bytes`);
